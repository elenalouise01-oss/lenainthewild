// A small best-effort limit on requests per visitor, kept in memory. Each
// server instance counts on its own, so this slows down scripted abuse
// rather than guaranteeing an exact cap.

const hits = new Map<string, number[]>();

export function rateLimited(key: string, limit: number, windowMs: number): boolean {
  const now = Date.now();
  const recent = (hits.get(key) ?? []).filter((t) => now - t < windowMs);
  recent.push(now);
  hits.set(key, recent);
  if (hits.size > 5000) {
    for (const [k, times] of hits) if (times.every((t) => now - t >= windowMs)) hits.delete(k);
  }
  return recent.length > limit;
}

export function clientKey(req: Request, bucket: string): string {
  const ip = req.headers.get('x-forwarded-for')?.split(',')[0]?.trim() || req.headers.get('x-real-ip') || 'unknown';
  return `${bucket}:${ip}`;
}
